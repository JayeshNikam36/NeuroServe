#!/usr/bin/env bash
# Compute Sanitizer over the KV, scheduler and GPU suites (Day 41, KV-004): memcheck (out-of-bounds
# and misaligned device memory accesses, invalid frees, CUDA API errors) and racecheck (shared-memory
# data races), each test binary under each tool. Full logs go to LOGS/*.log (the tool) and *.out
# (the tests); LOGS/compute-sanitizer.md summarizes them and is committed.
#
# Run it through CMake, which passes the paths:  cmake --build build/dev-cuda --target compute_sanitizer
# Exit status: 0 when every run passed its tests with zero sanitizer errors, 1 otherwise.
set -uo pipefail

if [[ $# -ne 5 ]]; then
    echo "usage: $0 COMPUTE_SANITIZER UNIT_TESTS CUDA_TESTS INTEGRATION_TESTS LOG_DIR" >&2
    exit 2
fi
SANITIZER=$1 UNIT=$2 CUDA=$3 INTEGRATION=$4 LOGS=$5
mkdir -p "$LOGS"

# racecheck instruments every shared-memory access, so its GPU run covers each kernel with the
# smallest tests that reach it: prefill (the engine's), decode (single and batched), prefill from a
# cached offset, copy-on-write and chunked prefill. memcheck runs everything.
RACECHECK_GPU='CudaLlmEngineBackendTest.SinglePromptMatchesHuggingFace:CudaLlmEngineBackendTest.AllPromptsDecodedTogetherMatchHuggingFace:CudaPrefixCacheTest.AnIdenticalPromptReusesEveryPageButTheLastAndMatches:CudaPrefixCacheTest.CopyOnWriteKeepsBothRequestsCorrect:CudaPrefixCacheTest.ChunkedPrefillReproducesHuggingFace'

# tool | suite | binary | gtest filter
RUNS=(
    "memcheck|unit|$UNIT|*"
    "memcheck|cuda|$CUDA|*"
    "memcheck|integration|$INTEGRATION|*"
    "racecheck|unit|$UNIT|*"
    "racecheck|cuda|$CUDA|*"
    "racecheck|integration|$INTEGRATION|$RACECHECK_GPU"
)

SUMMARY="$LOGS/compute-sanitizer.md"
{
    echo "# Compute Sanitizer"
    echo
    echo "$("$SANITIZER" --version | grep -m1 -i version) on $(nvidia-smi --query-gpu=name,driver_version --format=csv,noheader 2>/dev/null || echo 'an unknown GPU')."
    echo "Generated by \`scripts/compute_sanitizer.sh\` on $(date -u +%Y-%m-%dT%H:%MZ) at commit $(git rev-parse --short HEAD 2>/dev/null || echo unknown)."
    echo
    echo "| Tool | Suite | Tests | Result | Sanitizer errors | Minutes |"
    echo "| --- | --- | --- | --- | --- | --- |"
} > "$SUMMARY"

failed=0
for run in "${RUNS[@]}"; do
    IFS='|' read -r tool suite binary filter <<< "$run"
    log="$LOGS/$tool-$suite.log"
    out="$LOGS/$tool-$suite.out"
    echo "== $tool on the $suite tests ($(basename "$binary")) ..."
    start=$(date +%s)
    "$SANITIZER" --tool "$tool" --error-exitcode 99 --print-limit 50 --log-file "$log" \
        "$binary" --gtest_filter="$filter" --gtest_brief=1 > "$out" 2>&1
    status=$?
    minutes=$(awk -v s="$(( $(date +%s) - start ))" 'BEGIN { printf "%.1f", s / 60 }')

    # memcheck ends with "ERROR SUMMARY: N errors"; racecheck with "RACECHECK SUMMARY: N hazards
    # displayed (E errors, W warnings)". A missing line means the run did not finish.
    errors=$(grep -oE 'ERROR SUMMARY: [0-9]+' "$log" 2>/dev/null | tail -1 | grep -oE '[0-9]+$')
    if [[ "$tool" == racecheck ]]; then
        race=$(grep -oE 'RACECHECK SUMMARY: [0-9]+ hazards displayed \([0-9]+ errors' "$log" 2>/dev/null | tail -1 |
               grep -oE '\([0-9]+' | tr -d '(')
        errors=${race:-$errors}
    fi
    tests=$(grep -oE '\[==========\] [0-9]+ tests? from' "$out" | tail -1 | grep -oE '[0-9]+')
    failed_tests=$(grep -c '^\[  FAILED  \]' "$out")
    if [[ "${tests:-0}" == 0 ]]; then
        result="**ran no tests** (exit $status)"  # a filter that matches nothing proves nothing
        failed=1
    elif [[ $status -eq 0 && "${errors:-x}" == 0 ]]; then
        result="passed"
    elif [[ $status -eq 99 || ( -n "${errors:-}" && "$errors" != 0 ) ]]; then
        result="**sanitizer errors**"
        failed=1
    elif [[ $failed_tests -gt 0 ]]; then
        result="**tests failed**"
        failed=1
    else
        result="**did not finish** (exit $status)"
        failed=1
    fi
    echo "   $result: ${errors:-?} sanitizer errors, ${tests:-?} tests, $minutes min"
    echo "| $tool | $suite | ${tests:-?} | $result | ${errors:-?} | $minutes |" >> "$SUMMARY"
done

{
    echo
    echo "racecheck runs the GPU suite's smallest test for each kernel path; memcheck runs every test."
    echo "Full output: \`tests/logs/<tool>-<suite>.log\` (Compute Sanitizer) and \`.out\` (the tests), not committed."
} >> "$SUMMARY"
echo
cat "$SUMMARY"
exit $failed
